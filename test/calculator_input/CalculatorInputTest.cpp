// Run: c++ -std=c++20 test/calculator_input/CalculatorInputTest.cpp -o /tmp/calculator-input-test &&
// /tmp/calculator-input-test
#include <cassert>
#include <cstring>

#include "../../src/activities/tools/CalculatorFeedback.h"

int main() {
  CalculatorInput input;
  assert(std::strcmp(input.text, "0") == 0);
  constexpr char digits[] = {'0', '0', '7'};
  for (char digit : digits) assert(input.append(digit));
  assert(std::strcmp(input.text, "7") == 0);
  input.clear();
  input.clear();
  assert(input.length == 1 && std::strcmp(input.text, "0") == 0);
  assert(!input.append('C'));
  for (size_t i = 0; i < CalculatorInput::MAX_DIGITS; ++i) assert(input.append('8'));
  assert(input.full());
  assert(!input.append('9'));
  assert(std::strcmp(input.text, "888888888888") == 0);
  assert(input.append('.'));
  assert(!input.append('.'));
  assert(!input.append('9'));
  assert(std::strcmp(input.text, "888888888888.") == 0);
  input.clear();
  assert(input.append('.'));
  assert(!input.append('.'));
  assert(input.append('0'));
  assert(input.append('0'));
  assert(input.append('5'));
  assert(std::strcmp(input.text, "0.005") == 0);
  while (!input.full()) assert(input.append('0'));
  assert(input.length == CalculatorInput::MAX_DIGITS + 1);
  assert(input.text[input.length] == '\0');
  assert(!input.append('1'));
  assert(!input.append('+'));
  input.clear();
  assert(!input.hasDecimal);
  assert(input.append('1'));
  assert(std::strcmp(input.text, "1") == 0);
  input.backspace();
  assert(std::strcmp(input.text, "0") == 0);
  input.append('.');
  input.backspace();
  assert(!input.hasDecimal);
  input.append('.');
  input.append('5');
  input.backspace();
  assert(std::strcmp(input.text, "0.") == 0);

  CalculatorState calc;
  const auto enter = [&](const char* value) {
    for (; *value; ++value) calc.append(*value);
  };
  const auto expect = [&](const char* value) { assert(std::strcmp(calc.display(), value) == 0); };
  enter("12.5");
  calc.calculate('*');
  enter("2");
  calc.calculate('=');
  expect("25");
  calc.calculate('=');
  calc.backspace();
  expect("25");
  calc.calculate('-');
  enter("30");
  calc.calculate('=');
  expect("-5");
  enter("7");
  expect("7");
  calc.calculate('+');
  calc.calculate('*');
  enter("3");
  calc.calculate('+');
  expect("21");
  enter("4");
  calc.backspace();
  enter("2");
  calc.calculate('=');
  expect("23");
  calc.clear();
  enter("0.1");
  calc.calculate('+');
  enter("0.2");
  calc.calculate('=');
  expect("0.3");
  calc.clear();
  enter("1");
  calc.calculate('/');
  enter("3");
  calc.calculate('=');
  expect("0.333333333333");
  calc.calculate('/');
  enter("0");
  calc.calculate('=');
  assert(calc.error);
  enter("2");
  assert(!calc.error);
  expect("2");
  calc.clear();
  enter("999999999999");
  calc.calculate('*');
  enter("999999999999");
  calc.calculate('=');
  expect("9.99999999998e+23");
  calc.total = 1e308;
  calc.operation = '*';
  calc.fresh = true;
  enter("9");
  calc.calculate('=');
  assert(calc.error);
  calc.clear();
  expect("0");
  enter("5");
  calc.calculate('/');
  enter("2");
  calc.calculate('=');
  expect("2.5");
  calc.clear();
  calc.calculate('/');
  enter("0");
  calc.calculate('=');
  assert(calc.error);
  calc.calculate('+');
  assert(calc.error);
  calc.clear();
  assert(!calc.error);
  expect("0");
  enter("1");
  calc.calculate('/');
  enter("0");
  calc.calculate('=');
  assert(calc.error);
  calc.clearEntry();
  assert(!calc.error && calc.operation == 0);
  expect("0");
  enter("12");
  calc.calculate('+');
  calc.clearEntry();
  assert(calc.operation == '+' && calc.total == 12);
  enter("99");
  calc.clearEntry();
  calc.clearEntry();
  expect("0");
  assert(calc.operation == '+' && calc.total == 12);
  enter("3");
  calc.calculate('=');
  expect("15");
  assert(calc.operation == 0);
  calc.clearEntry();
  expect("0");
  enter("4");
  calc.calculate('=');
  expect("4");
  CalculatorFeedback feedback;
  CalculatorFeedback::Frame frame;
  feedback.take(frame);
  assert(frame.pressed == 0);
  calc.clear();
  for (int i = 1; i <= 5; ++i) {
    calc.append(static_cast<char>('0' + i));
    feedback.publish({calc, -1, uint32_t{1} << i});
  }
  feedback.take(frame);
  assert(frame.selected == -1);
  assert(frame.pressed == 0b111110);
  assert(std::strcmp(frame.calculator.display(), "12345") == 0);
  feedback.take(frame);
  assert(frame.pressed == 0);
  calc.clear();
  feedback.publish({calc, 10});
  feedback.take(frame);
  assert(std::strcmp(frame.calculator.display(), "0") == 0);
  assert(frame.selected == 10);
  assert(frame.pressed == 0);
  feedback.publish({calc, 3, uint32_t{1} << 7});
  feedback.publish({calc, 4, uint32_t{1} << 7});
  feedback.take(frame);
  assert(frame.selected == 4 && frame.pressed == (uint32_t{1} << 7));
  feedback.publish({calc, 4, uint32_t{1} << 8});
  feedback.take(frame);
  assert(frame.pressed == (uint32_t{1} << 8));
  const uint32_t one = uint32_t{1} << 1;
  const uint32_t two = uint32_t{1} << 2;
  feedback.shown(100, one);
  feedback.shown(200, two);
  assert(feedback.active == (one | two));
  assert(!feedback.clearDue(349));
  assert(feedback.clearDue(350));
  assert(feedback.active == two);
  assert(!feedback.clearDue(449));
  assert(feedback.clearDue(450));
  assert(feedback.active == 0);
  assert(!feedback.clearDue(451));
  feedback.shown(500, one | two);
  feedback.shown(600, two);
  assert(feedback.clearDue(750));
  assert(feedback.active == two);
  assert(feedback.clearDue(850));
  feedback.shown(UINT32_MAX - 100, one);
  assert(!feedback.clearDue(100));
  assert(feedback.clearDue(149));
  assert(feedback.active == 0);
  feedback.shown(500, 0);
  assert(!feedback.clearDue(900));
  // A second press arrives while the first snapshot is refreshing.
  feedback.publish({calc, -1, one});
  feedback.take(frame);
  const uint32_t firstPresses = frame.pressed;
  feedback.publish({calc, -1, two});
  feedback.shown(1000, firstPresses);
  feedback.take(frame);
  assert(frame.pressed == two && feedback.active == one);
  feedback.shown(1100, frame.pressed);
  assert(feedback.clearDue(1250));
  assert(feedback.active == two);
  feedback.take(frame);
  assert(frame.pressed == 0);
  assert(feedback.clearDue(1350));
}
